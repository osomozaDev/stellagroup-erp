-- Flujo comercial con demo: se solicita desde la oportunidad, la hacen los administradores
-- y, cuando está lista, le llega a quien la pidió con su URL.

alter table oportunidades drop constraint oportunidades_etapa_check;
update oportunidades set etapa = 'nuevo' where etapa = 'contactado';
update oportunidades set etapa = 'reunion_cierre' where etapa = 'reunion';
alter table oportunidades add constraint oportunidades_etapa_check
  check (etapa in ('nuevo', 'demo_solicitada', 'demo_lista', 'reunion_cierre', 'propuesta', 'ganado', 'perdido'));

alter table oportunidades
  add column numero int generated by default as identity,  -- referencia corta para contestar en Telegram
  add column sector text,
  add column requisitos text,                              -- la idea de lo que hay que crear
  add column demo_para date,
  add column demo_solicitada_en timestamptz,
  add column demo_solicitada_por uuid references auth.users(id) on delete set null,
  add column demo_asignados uuid[] not null default '{}',
  add column demo_evento_id uuid,                          -- sin clave foránea: una segunda relación con eventos rompería sus consultas
  add column demo_url text,
  add column demo_nota text,
  add column demo_lista_en timestamptz;
create unique index oportunidades_numero_idx on oportunidades(numero);
create index oportunidades_demo_pendiente_idx on oportunidades(demo_para) where etapa = 'demo_solicitada';
